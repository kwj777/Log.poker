/**
 * Encode the chip's URL as a QR matrix, into design/chip/qr.js.
 *
 *   node scripts/make-qr.mjs
 *
 * Run by `scripts/make-chip.mjs` before it rasterizes, so the code on the face
 * always comes from the URL rather than from whatever was pasted into a
 * generator's input box on the day somebody drew the chip.
 *
 * ## Why a committed matrix and not a library call in the page
 *
 * The faces are static HTML rendered by headless Chrome from a file:// URL, so
 * a page cannot reach a module. Writing the matrix out keeps the whole design
 * directory openable in a browser with no build step, and it makes the encoded
 * string a line in a diff rather than something only a render can show you.
 *
 * ## Why M rather than Q
 *
 * At this size the error-correction level trades against module size, and the
 * trade goes the other way from the intuition. This URL is 79 bytes:
 *
 *   L, M -> version 5, 37x37 modules
 *   Q    -> version 7, 45x45
 *   H    -> version 8, 49x49
 *
 * The tile is a fixed slice of a 47mm disc, so Q buys 10% more recovery and
 * pays for it with modules a fifth smaller. On a fired ceramic surface, which
 * does not scuff the way a sticker does, the bigger module is worth more than
 * the deeper redundancy: at M the face lands 0.43mm per module and at Q it
 * would be 0.35mm.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import QRCode from 'qrcode';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/**
 * The string that gets fired into a kiln.
 *
 * It is `chipUrl('qr')` from src/campaign/chip.ts, which is the single source
 * of truth for it, and the two are held together by a test rather than by a
 * comment: this file is .mjs and that one is TypeScript, so nothing else can
 * make one import the other.
 */
export const CHIP_QR_URL =
  'https://log.poker/chip?utm_source=protector&utm_medium=qr&utm_campaign=giveaway';

const ERROR_CORRECTION = 'M';

const qr = QRCode.create(CHIP_QR_URL, { errorCorrectionLevel: ERROR_CORRECTION });
const size = qr.modules.size;
const bits = Array.from(qr.modules.data, (bit) => (bit ? '1' : '0')).join('');

const file = `/* Generated by scripts/make-qr.mjs. Do not edit: run \`npm run chip\`.
 *
 * The chip's code, as a row-major bitmap. side-2.html draws it as one <rect>
 * per dark module, so what is fired into the glaze is this string and nothing
 * else has a chance to alter it between here and the kiln.
 */
window.CHIP_QR = {
  url: ${JSON.stringify(CHIP_QR_URL)},
  errorCorrection: ${JSON.stringify(ERROR_CORRECTION)},
  size: ${size},
  modules: ${JSON.stringify(bits)},
};
`;

writeFileSync(join(ROOT, 'design', 'chip', 'qr.js'), file);

console.log(
  `design/chip/qr.js  version ${qr.version}, ${size}x${size} at level ` +
    `${ERROR_CORRECTION}  <- ${CHIP_QR_URL}`,
);
