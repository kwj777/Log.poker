/**
 * The privacy policy, checked against the code it describes.
 *
 * Every sentence on that page is a claim about what this app does, and a claim
 * about behavior goes stale the way the front page's "no server to send
 * anything to" went stale: silently, on the day somebody shipped the server,
 * with nothing looking at it. `src/site/__tests__/site.test.ts` says at length
 * why a tripwire has to be anchored to the thing that makes a claim false
 * rather than to the claim. This file is that, for the page an app store holds
 * a link to.
 *
 * It is deliberately not a spell check of the prose. What is asserted here is
 * only the part a reader would be misled by: the named third parties, the
 * retention windows, the storage engines, and the promise that nothing leaves
 * without a sign-in.
 */
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

import { CODE_TTL_MS } from '../../auth/signinEndpoint';
import { TOKEN_TTL_MS } from '../../sync/verify';
import { ALLOW_SIGN_IN, PRIVACY_POLICY, SUPPORT_EMAIL } from '../../config';

const ROOT = join(__dirname, '..', '..', '..');
const read = (...parts: string[]): string => readFileSync(join(ROOT, ...parts), 'utf8');

const page = read('public', 'privacy.html');
const netlify = read('netlify.toml');
const home = read('public', 'home.html');
const sitemap = read('public', 'sitemap.xml');

const text = page
  .replace(/<[^>]+>/g, ' ')
  .replace(/&middot;/g, '.')
  .replace(/\s+/g, ' ')
  .trim();

describe('the page exists at the address everything points at', () => {
  it('is generated rather than hand-written, like the guides beside it', () => {
    expect(existsSync(join(ROOT, 'public', 'privacy.html'))).toBe(true);
    expect(read('scripts', 'build-content.mjs')).toContain("slug: '/privacy'");
    expect(page).toContain('Generated by scripts/build-content.mjs');
  });

  it('is served at the extensionless address it calls canonical', () => {
    // The same rule the guides get, and it matters more here: App Store
    // Connect stores this URL and a reviewer follows it, so "Netlify will
    // usually serve it" is a worse bet on this page than on any other.
    expect(page).toContain('<link rel="canonical" href="https://log.poker/privacy" />');
    expect(netlify).toContain('from = "/privacy"');
    expect(netlify).toContain('to = "/privacy.html"');
  });

  it('and the rule sits before the catch-all that would swallow it', () => {
    expect(netlify.indexOf('from = "/privacy"')).toBeLessThan(netlify.indexOf('from = "/app/*"'));
  });

  it('is what the app links to, spelled the same way in both places', () => {
    expect(PRIVACY_POLICY).toBe('https://log.poker/privacy');
  });

  it('is reachable from the site without knowing the address', () => {
    expect(home).toContain('href="/privacy"');
    // And from every generated page, which is what the footer link is for.
    for (const guide of ['running-bad', 'bankroll', 'pot-odds', 'tilt']) {
      expect(read('public', `${guide}.html`)).toContain('href="/privacy"');
    }
  });

  it('but is in neither sitemap, which is a rule rather than an oversight', () => {
    // The sitemaps list pages somebody arrives at from a search. This one is
    // reached on purpose, from a footer or from an app store listing.
    // `content.test.ts` asserts the XML list exactly, so adding it there is a
    // failing test rather than a judgment call; this says the same for the
    // page a person reads.
    expect(sitemap).not.toContain('/privacy');
  });
});

describe('what the page promises about leaving the device', () => {
  it('does not make the promise sync made false', () => {
    // The same sweep `site.test.ts` runs over the pages a visitor lands on.
    // A privacy policy is the worst possible place for the retired version of
    // this sentence to reappear.
    for (const promise of [
      /never leaves your device/i,
      /no server to send anything to/i,
      /keeps everything on your device/i,
      /never sends? (?:your log |anything |it )?anywhere/i,
    ]) {
      expect(text).not.toMatch(promise);
    }
  });

  it('makes the one that is true, and ties it to signing in', () => {
    expect(text).toMatch(/[Nn]othing leaves it unless you sign in/);
  });

  it('says signing in is optional, because it is', () => {
    // `ALLOW_SIGN_IN` gates the card, and nothing else in the app is gated on
    // a session: `SYNC_NEEDS_PASS` is off and the repository composes a plain
    // local one when there is no token.
    expect(text).toMatch(/every feature of Log works without an account/i);
  });
});

describe('what the page says is kept, and for how long', () => {
  it('names the storage engines the app actually uses', () => {
    expect(text).toMatch(/SQLite/);
    expect(text).toMatch(/IndexedDB/);
    expect(read('src', 'data', 'repositoryFactory.ts')).toMatch(/SqlRepository|expo-sqlite/);
    expect(read('src', 'data', 'repositoryFactory.web.ts')).toMatch(/Dexie/);
  });

  it('names where the token is held, on each platform', () => {
    expect(text).toMatch(/expo-secure-store/);
    expect(read('src', 'auth', 'tokenStore.ts')).toContain('expo-secure-store');
    expect(text).toMatch(/local storage/i);
    expect(read('src', 'auth', 'tokenStore.web.ts')).toMatch(/localStorage/);
  });

  it('quotes the sign-in code window that the endpoint enforces', () => {
    expect(CODE_TTL_MS).toBe(15 * 60 * 1000);
    expect(text).toMatch(/deleted fifteen minutes later/i);
  });

  it('quotes the token lifetime that verification enforces', () => {
    expect(TOKEN_TTL_MS).toBe(30 * 24 * 60 * 60 * 1000);
    expect(text).toMatch(/token lasts thirty days/i);
  });

  it('says the address is not stored, which is the endpoint’s own claim', () => {
    expect(text).toMatch(/keyed by a one-way fingerprint of the address/i);
    // Asserted against the module that would have to change for it to stop
    // being true, rather than against a comment restating it.
    const endpoint = read('src', 'auth', 'signinEndpoint.ts');
    expect(endpoint).toContain('subjectForEmail');
    expect(read('src', 'sync', 'verify.ts')).toContain('hmacHex');
  });
});

describe('who the page says touches it', () => {
  it('names both, and the code reaches exactly those two', () => {
    expect(text).toMatch(/Netlify/);
    expect(text).toMatch(/Resend/);
    expect(read('netlify', 'functions', 'signin.mts')).toContain('api.resend.com');
    expect(read('netlify', 'functions', 'sync.mts')).toContain('@netlify/blobs');
  });

  it('claims no analytics, and the app ships none', () => {
    expect(text).toMatch(/no analytics/i);
    // The page is the promise; this is the thing that makes it false. A
    // dependency is where one of these arrives, so that is where to look.
    const manifest = JSON.parse(read('package.json')) as {
      dependencies: Record<string, string>;
    };
    const trackers = /sentry|analytics|segment|mixpanel|amplitude|posthog|firebase|bugsnag|appsflyer|adjust|branch/i;
    expect(Object.keys(manifest.dependencies).filter((name) => trackers.test(name))).toEqual([]);
  });
});

describe('how the page says to delete it', () => {
  it('names the control by the label the app actually shows', () => {
    // Two files and one string between them. A relabeled button and a page
    // still naming the old one sends somebody hunting for a control that is
    // right in front of them.
    const copy = read('src', 'features', 'account', 'copy.ts');
    const label = /export const DELETE_ACCOUNT = '([^']+)'/.exec(copy)?.[1];
    expect(label).toBe('Delete your account and its data');
    expect(text).toContain(label as string);
    expect(read('src', 'features', 'account', 'SignInCard.tsx')).toContain('label={DELETE_ACCOUNT}');
  });

  it('and the section of Settings it is in', () => {
    expect(text).toMatch(/Your other devices/);
    expect(read('app', '(tabs)', 'settings.tsx')).toContain('title="Your other devices"');
  });

  it('says there is nothing else left afterwards, which is why there is no second step', () => {
    expect(text).toMatch(/no account record left behind/i);
  });
  it('gives a way to do it from a browser, without the app', () => {
    // Google Play wants a web page where a player who has uninstalled can
    // still ask for deletion, naming the app as its listing does, ideally
    // reached by an anchor. The web build renders the same Settings card, so
    // the browser route is real as long as sign-in is on and the route exists.
    expect(page).toContain('<section id="delete">');
    expect(page).toContain('href="/app/settings"');
    expect(existsSync(join(ROOT, 'app', '(tabs)', 'settings.tsx'))).toBe(true);
    expect(ALLOW_SIGN_IN).toBe(true);
    expect(text).toContain('Log: Poker Session Tracker');
  });
});

describe('how the page says to reach a person', () => {
  it('gives the address the app gives, once, as a working link', () => {
    expect(SUPPORT_EMAIL).toBe('support@log.poker');
    expect(page).toContain(`mailto:${SUPPORT_EMAIL}`);
    expect(read('app', '(tabs)', 'settings.tsx')).toContain('SUPPORT_EMAIL');
  });
});
